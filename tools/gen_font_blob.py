"""Writes src/supervision/_cv/font/rubik_data.mojo from the gzipped Rubik that cv2 5.0 embeds as its built-in "sans" font
(third gzip stream in cv2.abi3.so that decodes to a TrueType font named "Rubik for OpenCV Light Regular").
The raw stream is also kept as src/supervision/_cv/font/Rubik-sans.ttf.gz. Run with .work/oracle-venv/bin/python -I tools/gen_font_blob.py"""
import io
import re
import zlib

import cv2
from fontTools.ttLib import TTFont

so = open(cv2.__file__.replace("__init__.py", "cv2.abi3.so"), "rb").read()
found = None
for m in re.finditer(b"\x1f\x8b\x08", so):
    d = zlib.decompressobj(31)
    try:
        out = d.decompress(so[m.start() : m.start() + 3_000_000])
    except zlib.error:
        continue
    if len(out) > 20000 and out[:4] == b"\x00\x01\x00\x00":
        nm = TTFont(io.BytesIO(out))["name"]
        if (nm.getDebugName(1), nm.getDebugName(2)) == ("Rubik for OpenCV Light", "Regular"):
            found = so[m.start() : m.start() + 3_000_000][: 3_000_000 - len(d.unused_data)]
assert found, "sans font not found in cv2"
open("src/supervision/_cv/font/Rubik-sans.ttf.gz", "wb").write(found)
hx = found.hex()
lines = [hx[i : i + 100] for i in range(0, len(hx), 100)]
body = "\n".join(f'    "{ln}"' for ln in lines)
open("src/supervision/_cv/font/rubik_data.mojo", "w").write(
    "# Rubik (OFL-1.1), the gzipped TrueType cv2 5.0 embeds as its built-in \"sans\" font, as hex; generated by\n"
    "# tools/gen_font_blob.py from the cv2 wheel (do not edit). Decode with supervision._cv.font.load_sans().\n"
    f"comptime RUBIK_SANS_GZ_HEX = (\n{body}\n)\n"
)
print(len(found), "gz bytes,", len(lines), "lines")
