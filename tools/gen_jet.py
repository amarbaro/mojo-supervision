"""Writes src/supervision/_cv/jet.mojo: cv2's COLORMAP_JET lookup table (256 x BGR), read back from cv2 itself.
Run with .work/oracle-venv/bin/python -I tools/gen_jet.py"""
import cv2
import numpy as np

lut = cv2.applyColorMap(np.arange(256, dtype=np.uint8).reshape(256, 1), cv2.COLORMAP_JET).reshape(256, 3)
text = " ".join(f"{b},{g},{r}" for b, g, r in lut.tolist())
rows, cur = [], ""
for t in text.split(" "):
    if len(cur) + len(t) > 100:
        rows.append(cur)
        cur = ""
    cur += t + " "
rows.append(cur)
body = "\n".join(f'    "{r.strip()} "' for r in rows)
open("src/supervision/_cv/jet.mojo", "w").write(
    "# cv2.COLORMAP_JET as a 256 x BGR table; generated by tools/gen_jet.py from cv2 5.0 (do not edit).\n"
    f"comptime JET_TEXT = (\n{body}\n)\n"
)
